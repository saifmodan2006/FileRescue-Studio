import {drizzle} from 'drizzle-orm/node-postgres';
import {sql} from 'drizzle-orm';
import type {SQL} from 'drizzle-orm';
import pg from 'pg';

const initialSchema = `
  CREATE TABLE admin_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username text NOT NULL UNIQUE, password text NOT NULL
  );
  CREATE TABLE admin_sessions (
    hash text PRIMARY KEY, admin_id integer NOT NULL REFERENCES admin_users ON DELETE CASCADE,
    csrf text NOT NULL, expires bigint NOT NULL
  );
  CREATE INDEX sessions_expires ON admin_sessions (expires);
  CREATE TABLE feedback (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category text NOT NULL, message text NOT NULL,
    state text NOT NULL DEFAULT 'new', created bigint NOT NULL
  );
  CREATE TABLE consented_usage_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, format text NOT NULL, outcome text NOT NULL, created bigint NOT NULL
  );
  CREATE INDEX usage_created ON consented_usage_events (created);
  CREATE TABLE application_settings (
    id integer PRIMARY KEY CHECK(id=1), feedback_enabled boolean NOT NULL DEFAULT true,
    analytics_enabled boolean NOT NULL DEFAULT false, announcement text NOT NULL DEFAULT ''
  );
  INSERT INTO application_settings (id) VALUES (1);
`;

const migrations = [initialSchema];

export async function openPostgres(connectionString: string, onPoolError?: (code:string) => void) {
  const connection = URL.parse(connectionString);
  if (!connection || !['postgresql:','postgres:'].includes(connection.protocol) || connection.pathname.length < 2) {
    throw new Error('DATABASE_URL must identify a PostgreSQL database.');
  }
  // The driver lets URL SSL options replace explicit TLS options. Pass only
  // the endpoint and credentials, and manage certificate verification here.
  connection.search = '';
  const local = ['localhost','127.0.0.1','[::1]'].includes(connection.hostname);
  const pool = new pg.Pool({
    connectionString:connection.href,
    ssl:local ? false : {rejectUnauthorized:true},
    enableChannelBinding:!local,
    max:3, idleTimeoutMillis:10_000, connectionTimeoutMillis:10_000,
    query_timeout:12_000,
  });
  pool.on('error',error => onPoolError?.((error as Error & {code?:string}).code ?? error.name));
  const db = drizzle(pool);
  try {
    await db.transaction(async tx => {
      await tx.execute(sql`SELECT pg_advisory_xact_lock(594729, 141)`);
      await tx.execute(sql`CREATE TABLE IF NOT EXISTS studio_migrations (version integer PRIMARY KEY)`);
      const result = await tx.execute<{version:number}>(sql`SELECT version FROM studio_migrations ORDER BY version`);
      const applied = result.rows.map(row => row.version);
      if (applied.some((version,index) => version !== index + 1 || version > migrations.length)) {
        throw new Error('Unrecognized PostgreSQL migration history.');
      }
      for (let index = applied.length; index < migrations.length; index++) {
        await tx.execute(sql.raw(migrations[index]));
        await tx.execute(sql`INSERT INTO studio_migrations (version) VALUES (${index + 1})`);
      }
    });
  } catch (error) {
    await pool.end();
    throw error;
  }
  return {
    rows:async <T extends Record<string,unknown>>(query:SQL) => (await db.execute<T>(query)).rows,
    batch:async (queries:SQL[]) => db.transaction(async tx => {
      for (const query of queries) await tx.execute(query);
    }),
    close:() => pool.end(),
  };
}
